const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const temp = fs.mkdtempSync(path.join(os.tmpdir(),'slide-history-test-'));
const source = fs.readFileSync(path.join(__dirname,'../Editor/server.js'),'utf8');
const context = vm.createContext({require,process:{argv:['node','server.js'],env:{}},__dirname:path.join(__dirname,'../Editor'),console,Buffer,URL});
vm.runInContext(source.slice(0,source.lastIndexOf('\ntry {\n')),context);
const run = code => vm.runInContext(code,context);
const configPath = path.join(temp,'config.json');
const out = path.join(temp,'output');fs.mkdirSync(out);
const slides = [{id:'first',screenshot:'one.png',captions:{en_US:'One'},loupes:{iphone:{zoom:2}}},{id:'second',screenshot:'two.png',captions:{en_US:'Two'}}];
fs.writeFileSync(configPath,JSON.stringify({devices:{iphone:{screenshotRoot:temp}},slides}));
fs.writeFileSync(path.join(temp,'one.png'),'input');fs.writeFileSync(path.join(temp,'two.png'),'input2');
for(const slide of slides)fs.writeFileSync(path.join(out,slide.id+'.png'),slide.id);
context.fixtureSet={id:'current',configPath,outputDir:out,device:'iphone',locale:'en_US',version:'v1.0.0',editable:true};
run(`allSlideSets=()=>[fixtureSet];editorState=()=>({sets:[fixtureSet],activeSetId:'current'});`);
const ids=()=>JSON.parse(fs.readFileSync(configPath)).slides.map(x=>x.id);
const history=(token,present)=>{context.historyPayload={token,present};return run('restoreSlideChange(historyPayload)');};
try {
 const duplicate=run(`duplicateSlide({setId:'current',slideId:'first'})`);
 const deletion=run(`deleteSlide({setId:'current',slideId:'first-copy'})`);
 assert.deepEqual(ids(),['first','second']);
 assert.equal(deletion.selectedSlideId,'second');
 assert.equal(fs.existsSync(path.join(out,'first-copy.png')),false);
 assert.equal(fs.readFileSync(path.join(temp,'first-copy.png'),'utf8'),'input');
 history(deletion.slideChangeToken,true);
 assert.deepEqual(ids(),['first','first-copy','second']);
 assert.equal(fs.readFileSync(path.join(out,'first-copy.png'),'utf8'),'first');
 history(duplicate.slideChangeToken,false);
 assert.deepEqual(ids(),['first','second']);
 history(duplicate.slideChangeToken,true);
 history(deletion.slideChangeToken,false);
 assert.deepEqual(ids(),['first','second']);
 assert.throws(()=>history(deletion.slideChangeToken,false),/already applied/);
 assert.throws(()=>history('unknown',true),/unavailable/);
 assert.throws(()=>run(`deleteSlide({setId:'old',slideId:'first'})`),/Only current/);
 const removed=run(`deleteSlide({setId:'current',slideId:'first'})`);
 assert.deepEqual(ids(),['second']);
 assert.throws(()=>run(`deleteSlide({setId:'current',slideId:'second'})`),/at least one/);
 assert.equal(fs.readFileSync(path.join(temp,'one.png'),'utf8'),'input');
 history(removed.slideChangeToken,true);
 assert.deepEqual(ids(),['first','second']);
 const config=JSON.parse(fs.readFileSync(configPath));assert.deepEqual(config.slides[0],slides[0]);
 console.log('Slide history: duplicate/delete undo-redo, ordering, images, settings, selection, read-only and last-slide guards passed');
} finally {
 for(const change of run('[...slideChanges.values()]'))fs.rmSync(change.hidden,{recursive:true,force:true});
 fs.rmSync(temp,{recursive:true,force:true});
}
